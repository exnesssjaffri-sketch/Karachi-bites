-- Advance the IDENTITY sequence past the highest explicit seed ID.
-- GENERATED BY DEFAULT AS IDENTITY does NOT advance the sequence when explicit
-- IDs are inserted, so without this the next admin menu insert (which relies on
-- the column DEFAULT) would collide with the hardcoded IDs 1-12.
--
-- The previous `COALESCE(MAX(id), 0)` fallback is invalid: `setval(seq, 0)`
-- violates the sequence's MINVALUE 1 constraint. We now use
-- `pg_get_serial_sequence` to resolve the actual sequence name and branch on
-- the table state:
--   * Empty table  -> setval(seq, 1, false)  (is_called=false so the next
--     nextval returns 1, the minimum legal value).
--   * Existing rows -> setval(seq, max, true) (is_called=true so the next
--     nextval returns max+1, never colliding with existing IDs).
-- Safe to re-run; idempotent.
DO $$
DECLARE
  v_seq text;
  v_max bigint;
BEGIN
  v_seq := pg_get_serial_sequence('public.menu_items', 'id');
  IF v_seq IS NULL THEN
    RAISE NOTICE 'No serial sequence found for public.menu_items; skipping sequence advance.';
    RETURN;
  END IF;

  SELECT MAX(id) INTO v_max FROM public.menu_items;

  IF v_max IS NULL THEN
    -- Empty table: start the sequence at 1 without marking it as called,
    -- so the next nextval() returns 1 (the sequence minimum).
    EXECUTE format('SELECT setval(%L, 1, false)', v_seq);
  ELSE
    -- Existing rows: mark the sequence as called at the current maximum so
    -- the next nextval() returns max + 1 and never collides.
    EXECUTE format('SELECT setval(%L, %L, true)', v_seq, v_max);
  END IF;
END
$$;
